// Provider-specific constants.
const (
	providerName = "infobloxnios"
	apiVersion   = "v1alpha1"
	// modulePath is the Go module path declared in the provider root's
	// go.mod. Used to build fully-qualified
	// +crossplane:generate:reference:type marker values for future
	// cross-resource reference fields (none exist on ARecord today).
	modulePath = "github.com/crossplane-contrib/provider-infoblox-nios"
)

// FieldData is the template data for a single struct field.
type FieldData struct {
	// Name is the Go field name (PascalCase).
	Name string
	// GoType is the full Go type string (e.g. "*bool", "[]string").
	GoType string
	// JSONName is the JSON serialisation key.
	JSONName string
	// Description is a human-readable description (used as a Go doc comment).
	Description string
	// OmitEmpty controls whether the JSON tag includes omitempty.
	OmitEmpty bool
	// Required controls whether a +kubebuilder:validation:Required marker is
	// emitted (ForProvider fields only).
	Required bool
	// Immutable is true for ForProvider fields that require a CEL
	// XValidation rule.
	Immutable bool
	// Enum lists valid string values for this field.
	Enum []string
	// HasMinimum controls whether a +kubebuilder:validation:Minimum
	// marker is emitted (ForProvider fields only).
	HasMinimum bool
	// Minimum is the marker value rendered when HasMinimum is true.
	Minimum int64
	// HasMaximum controls whether a +kubebuilder:validation:Maximum
	// marker is emitted (ForProvider fields only).
	HasMaximum bool
	// Maximum is the marker value rendered when HasMaximum is true.
	Maximum int64
	// Reference holds cross-resource reference template data. Nil for
	// every ARecord field today.
	Reference *ReferenceData
	// ExtraValidations are field-level kubebuilder XValidation rules
	// (catalog.FieldDef.ForProviderValidations). Rendered ONLY on
	// ForProvider fields — buildAtProviderFieldData never populates
	// this, so the same underlying catalog rule (e.g. the reserved
	// extAttrs identity key) never reaches the AtProvider mirror.
	ExtraValidations []catalog.ValidationRule
}

// ReferenceData is the template data for one field's cross-resource
// reference. Not populated by any current resource — retained so the
// template already supports it when a referencing resource (e.g.
// CNAMERecord) is added.
type ReferenceData struct {
	// MarkerType is the fully-qualified Go type reference for the
	// +crossplane:generate:reference:type marker.
	MarkerType string
	// MarkerExtractor is the value for the
	// +crossplane:generate:reference:extractor marker. Empty omits the
	// marker, so angryjet falls back to reference.ExternalName().
	MarkerExtractor string
	// RefFieldName is the Go field name of the reference field.
	RefFieldName string
	// RefFieldJSONName is the camelCase JSON name for RefFieldName.
	RefFieldJSONName string
	// RefGoType is the Go type of the reference field.
	RefGoType string
	// RefFieldOmitEmpty is false when RefGoType is a slice, true otherwise.
	RefFieldOmitEmpty bool
	// SelectorFieldName is the Go field name of the selector field.
	SelectorFieldName string
	// SelectorGoType is "*xpv2.Reference"-style selector type.
	SelectorGoType string
	// SelectorFieldJSONName is the camelCase JSON name for SelectorFieldName.
	SelectorFieldJSONName string
}

// NestedTypeData is the template data for a custom nested struct type.
type NestedTypeData struct {
	// TypeName is the Go type name (e.g. "ARecordDiscoveredData").
	TypeName string
	// Description is the type's doc comment.
	Description string
	// Fields are the fields of this struct.
	Fields []FieldData
}

// FieldSetData is the template input shared by both the standalone reference
// copy (apis/common/<slug>) and each scope's self-contained types file
// (apis/{cluster,namespaced}/<slug>/v1alpha1).
type FieldSetData struct {
	// Kind is the Kubernetes Kind (e.g. "ARecord").
	Kind string
	// Slug is the directory slug (e.g. "recorda"), used for file paths
	// and the apis/common/<slug> directory name.
	Slug string
	// PackageName is the Go package identifier for the standalone
	// apis/common/<slug> reference copy. Equal to Slug for almost every
	// resource, EXCEPT when Slug collides with a Go reserved keyword
	// (e.g. "range" — CreateNetworkRange's resource slug), in which case
	// it is Slug with a "pkg" suffix so `package {{.PackageName}}`
	// compiles. See safeGoPackageName.
	PackageName string
	// ForProvider contains fields sent in API create/update requests.
	ForProvider []FieldData
	// AtProvider contains fields populated from API responses. This is a
	// full mirror of ForProvider plus response-only fields.
	AtProvider []FieldData
	// NestedTypes contains custom struct type definitions referenced by
	// fields (e.g. ARecordDiscoveredData).
	NestedTypes []NestedTypeData
	// HasReferences is true if any ForProvider or nested-type field
	// carries a cross-resource Reference.
	HasReferences bool
	// ParameterValidations are resource-level (cross-field) CEL
	// XValidation rules rendered on the {{.Kind}}Parameters struct.
	ParameterValidations []catalog.ValidationRule
	// NeedsXPV2Import is true if any field (top-level or nested,
	// ForProvider or AtProvider) has a Go type that references the xpv2
	// package directly (implied by any cross-resource Reference). The
	// standalone common reference copy only imports xpv2 when this is
	// true — every scope's self-contained types file already imports
	// xpv2 unconditionally for xpv2.ClusterManagedResourceSpec/
	// ManagedResourceSpec/ManagedResourceStatus.
	NeedsXPV2Import bool
}

// ScopeData is the template input for a scope-specific (cluster/namespaced)
// MR types file. It embeds FieldSetData so the scope template can render
// self-contained Parameters/Observation/nested types alongside the MR
// wrapper (Spec/Status/Kind/KindList).
type ScopeData struct {
	FieldSetData
	// Scope is "Cluster" or "Namespaced".
	Scope string
	// IsCluster is true for the cluster-scoped variant.
	IsCluster bool
	// Group is the full API group for this scope
	// (e.g. "recorda.infobloxnios.crossplane.io").
	Group string
	// DriftDetectionImportPath is the fully-qualified import path of the
	// shared apis/common/driftdetection package, imported (unlike the
	// per-resource types) by every scope package's Spec.
	DriftDetectionImportPath string
}

// isOmitEmpty reports whether a Go type should use omitempty in its JSON
// struct tag, given whether the field is required.
//
// Slice ([]T) and map (map[K]V) fields MUST NOT use omitempty, in ANY
// struct (ForProvider, AtProvider, or nested types) — empty collections
// must round-trip as [] / {} rather than null so CEL `self == oldSelf`
// immutability rules never see a spurious null diff. Scalar/pointer fields
// use omitempty when the field is not required.
func isOmitEmpty(goType string, required bool) bool {
	if strings.HasPrefix(goType, "[]") || strings.HasPrefix(goType, "map[") {
		return false
	}
	return !required
}

// usesXPV2 reports whether a Go type string references the xpv2 package
// directly (e.g. "xpv2.Reference"). Used to decide whether the standalone
// common reference copy needs to import xpv2.
func usesXPV2(goType string) bool {
	return strings.Contains(goType, "xpv2.")
}

// lowerFirst lowercases the first rune of s, leaving the rest untouched.
func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// safeGoPackageName returns a resource slug that is guaranteed to be a
// valid Go package identifier. It is used only for the standalone
// apis/common/<slug> reference copy's `package` declaration — every other
// use of a resource slug (directory names, CRD/API group names, JSON field
// names) is a string literal or filesystem path, not a Go identifier, and
// is unaffected by keyword collisions. A resource slug that happens to be
// a Go reserved word (e.g. "range", from CreateNetworkRange) would
// otherwise render an uncompilable `package range` — appending "pkg"
// disambiguates it while keeping the directory/CRD-facing slug untouched.
func safeGoPackageName(slug string) string {
	if token.IsKeyword(slug) {
		return slug + "pkg"
	}
	return slug
}

// buildReferenceData converts a catalog.ReferenceDescriptor into template
// data for the value field named goFieldName with Go type goType.
func buildReferenceData(ref *catalog.ReferenceDescriptor, goFieldName, goType string, isCluster bool) *ReferenceData {
	if ref == nil {
		return nil
	}

	scope := ref.TargetScope
	if scope == "" {
		scope = "namespaced"
		if isCluster {
			scope = "cluster"
		}
	}

	refType, selectorType := "xpv2.Reference", "xpv2.Selector"
	if !isCluster {
		refType, selectorType = "xpv2.NamespacedReference", "xpv2.NamespacedSelector"
	}

	refFieldName := goFieldName + "Ref"
	refGoType := "*" + refType
	if strings.HasPrefix(goType, "[]") {
		refFieldName = goFieldName + "Refs"
		refGoType = "[]" + refType
	}
	selectorFieldName := goFieldName + "Selector"

	return &ReferenceData{
		MarkerType:            fmt.Sprintf("%s/apis/%s/%s/%s.%s", modulePath, scope, ref.TargetSlug, apiVersion, ref.TargetKind),
		MarkerExtractor:       ref.Extractor,
		RefFieldName:          refFieldName,
		RefFieldJSONName:      lowerFirst(refFieldName),
		RefGoType:             refGoType,
		RefFieldOmitEmpty:     isOmitEmpty(refGoType, false),
		SelectorFieldName:     selectorFieldName,
		SelectorGoType:        "*" + selectorType,
		SelectorFieldJSONName: lowerFirst(selectorFieldName),
	}
}

// buildFieldData converts one catalog.FieldDef into ForProvider FieldData.
func buildFieldData(f catalog.FieldDef, isCluster bool) FieldData {
	fd := FieldData{
		Name:             f.Name,
		GoType:           f.GoType,
		JSONName:         f.JSONName,
		Description:      f.Description,
		OmitEmpty:        isOmitEmpty(f.GoType, f.Required),
		Required:         f.Required,
		Immutable:        f.Immutable,
		Enum:             f.Enum,
		Reference:        buildReferenceData(f.Reference, f.Name, f.GoType, isCluster),
		ExtraValidations: f.ForProviderValidations,
	}
	if f.Minimum != nil {
		fd.HasMinimum = true
		fd.Minimum = *f.Minimum
	}
	if f.Maximum != nil {
		fd.HasMaximum = true
		fd.Maximum = *f.Maximum
	}
	return fd
}

// atProviderGoType returns the Go type to use for a field mirrored into the
// Observation struct. AtProvider fields are always optional (the value may
// not be observed yet), so non-pointer, non-collection ForProvider types
// (e.g. "string") are mirrored as pointers (e.g. "*string"). Types that are
// already pointers, slices, or maps are copied as-is.
func atProviderGoType(goType string) string {
	if strings.HasPrefix(goType, "*") || strings.HasPrefix(goType, "[]") || strings.HasPrefix(goType, "map[") {
		return goType
	}
	return "*" + goType
}

// buildAtProviderFieldData converts one catalog.FieldDef into AtProvider
// FieldData. AtProvider fields always use omitempty, except slice/map fields
// (which never carry omitempty). Immutable is carried over so the
// Observation template can emit a CEL `self == oldSelf` rule on the mirror
// field — this is the ONLY place a response-only (FieldScopeResponse)
// immutable field can carry the rule at all, since it has no ForProvider
// counterpart to attach it to.
func buildAtProviderFieldData(f catalog.FieldDef) FieldData {
	goType := atProviderGoType(f.GoType)
	return FieldData{
		Name:        f.Name,
		GoType:      goType,
		JSONName:    f.JSONName,
		Description: f.Description,
		OmitEmpty:   isOmitEmpty(goType, false),
		Immutable:   f.Immutable,
	}
}

// BuildFieldSetData converts a catalog.ResourceDescriptor into the shared
// field-set template data consumed by both the standalone reference copy and
// every scope's self-contained types file. isCluster selects which scope's
// import path is used for any cross-resource reference; the standalone
// common reference copy always renders with isCluster=true purely for a
// single deterministic doc-only rendering (see Generate).
//
// Field-scope mapping:
//
//	FieldScopeRequest  -> ForProvider only
//	FieldScopeResponse -> AtProvider only
//	FieldScopeBoth     -> BOTH ForProvider and AtProvider
//
// All ForProvider fields also appear in AtProvider (full-mirror) to enable
// Observe-mode import — EXCEPT fields marked catalog.FieldDef.
// OmitFromObservation, which the API genuinely never echoes back (e.g.
// ARecord's and AAAARecord's removeAssociatedPtr, ExtensibleAttributeDef's
// descendantsAction, RangeTemplate's msServer). Those fields still appear
// in ForProvider normally; only the AtProvider mirror is skipped.
func BuildFieldSetData(rd catalog.ResourceDescriptor, isCluster bool) FieldSetData {
	var forProvider, atProvider []FieldData
	hasReferences := false
	needsXPV2 := false

	for _, f := range rd.Fields {
		switch f.Scope {
		case catalog.FieldScopeRequest, catalog.FieldScopeBoth:
			forProvider = append(forProvider, buildFieldData(f, isCluster))
			if !f.OmitFromObservation {
				atProvider = append(atProvider, buildAtProviderFieldData(f))
			}
		case catalog.FieldScopeResponse:
			if !f.OmitFromObservation {
				atProvider = append(atProvider, buildAtProviderFieldData(f))
			}
		}
		if f.Reference != nil {
			hasReferences = true
		}
		if usesXPV2(f.GoType) {
			needsXPV2 = true
		}
	}

	nestedTypes := make([]NestedTypeData, 0, len(rd.NestedTypes))
	for _, nt := range rd.NestedTypes {
		fields := make([]FieldData, 0, len(nt.Fields))
		for _, f := range nt.Fields {
			fields = append(fields, FieldData{
				Name:        f.Name,
				GoType:      f.GoType,
				JSONName:    f.JSONName,
				Description: f.Description,
				// No omitempty on slice/map, even in nested types. Nested
				// types can carry genuinely required fields (e.g. a list
				// entry's identifying value) — honor Required the same way
				// top-level fields do.
				OmitEmpty: isOmitEmpty(f.GoType, f.Required),
				Required:  f.Required,
				Reference: buildReferenceData(f.Reference, f.Name, f.GoType, isCluster),
			})
			if f.Reference != nil {
				hasReferences = true
			}
			if usesXPV2(f.GoType) {
				needsXPV2 = true
			}
		}
		nestedTypes = append(nestedTypes, NestedTypeData{
			TypeName:    nt.TypeName,
			Description: nt.Description,
			Fields:      fields,
		})
	}

	return FieldSetData{
		Kind:                 rd.Kind,
		Slug:                 rd.Slug,
		PackageName:          safeGoPackageName(rd.Slug),
		ForProvider:          forProvider,
		AtProvider:           atProvider,
		NestedTypes:          nestedTypes,
		HasReferences:        hasReferences,
		ParameterValidations: rd.ParameterValidations,
		NeedsXPV2Import:      needsXPV2 || hasReferences,
	}
}

// BuildScopeData converts a catalog.ResourceDescriptor into template data for
// one scope's self-contained types file.
func BuildScopeData(rd catalog.ResourceDescriptor, isCluster bool) ScopeData {
	scope := "Namespaced"
	group := rd.NamespacedGroup
	if isCluster {
		scope = "Cluster"
		group = rd.ClusterGroup
	}
	return ScopeData{
		FieldSetData:             BuildFieldSetData(rd, isCluster),
		Scope:                    scope,
		IsCluster:                isCluster,
		Group:                    group,
		DriftDetectionImportPath: modulePath + "/apis/common/driftdetection",
	}
}

// templateFuncs are helper functions available in all generator templates.
var templateFuncs = template.FuncMap{
	// jsonTag produces a complete struct tag literal: `json:"name"` or
	// `json:"name,omitempty"`.
	"jsonTag": func(name string, omitEmpty bool) string {
		if omitEmpty {
			return "`" + `json:"` + name + `,omitempty"` + "`"
		}
		return "`" + `json:"` + name + `"` + "`"
	},
	"inlineTag": func() string {
		return "`" + `json:",inline"` + "`"
	},
	// enumValues renders a kubebuilder Enum marker's value list.
	"enumValues": func(vals []string) string {
		return strings.Join(vals, ";")
	},
	// isSliceType reports whether a Go type string is a slice ("[]T").
	"isSliceType": func(goType string) bool {
		return strings.HasPrefix(goType, "[]")
	},
}

