// renderTemplate executes a named template and gofmt-formats the result.
func renderTemplate(name, tmpl string, data any, kind string) ([]byte, error) {
	t, err := template.New(name).Funcs(templateFuncs).Parse(tmpl)
	if err != nil {
		return nil, fmt.Errorf("parsing %s template: %w", name, err)
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("executing %s template for %s: %w", name, kind, err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		// Return the unformatted source for debugging alongside the error.
		return buf.Bytes(), fmt.Errorf("formatting %s for %s (raw source returned): %w", name, kind, err)
	}
	return src, nil
}

// Generate produces all Go source files for rd in both cluster-scoped and
// namespaced scopes, plus the standalone common reference copy. outputDir is
// the provider root (e.g. "." when running from provider-infobloxnios/).
//
// Files written:
//   - apis/common/<package-name>/<package-name>_types.go — <package-name> is
//     rd.Slug UNLESS rd.Slug is a Go reserved keyword (e.g. "range"), in
//     which case it is safeGoPackageName(rd.Slug) (e.g. "rangepkg"). The
//     directory name always matches the package name so `go run
//     ./... generate-methodsets` (jennifer's NewFilePath, which derives the
//     package clause it writes from the LAST PATH SEGMENT of the import
//     path, not the file's actual `package` declaration) never emits an
//     uncompilable `package range`.
//   - apis/cluster/<slug>/v1alpha1/{doc.go,register.go,<slug>_types.go}
//   - apis/namespaced/<slug>/v1alpha1/{doc.go,register.go,<slug>_types.go}
func Generate(rd catalog.ResourceDescriptor, outputDir string) error {
	// Standalone common reference copy (isCluster=true is an arbitrary,
	// deterministic choice — the common copy documents the field list,
	// it does not need scope-specific import paths since ARecord has no
	// cross-resource reference fields).
	commonData := BuildFieldSetData(rd, true)
	commonSrc, err := RenderCommonReference(commonData)
	if err != nil {
		return fmt.Errorf("rendering common reference for %s: %w", rd.Kind, err)
	}
	commonDir := filepath.Join(outputDir, "apis", "common", commonData.PackageName)
	commonFile := filepath.Join(commonDir, commonData.PackageName+"_types.go")
	if err := writeFile(commonFile, commonSrc); err != nil {
		return err
	}

	// Scope-specific packages (self-contained).
	for _, isCluster := range []bool{true, false} {
		scope := "namespaced"
		if isCluster {
			scope = "cluster"
		}

		pkgDir := filepath.Join(outputDir, "apis", scope, rd.Slug, apiVersion)
		if err := os.MkdirAll(pkgDir, 0o750); err != nil {
			return fmt.Errorf("creating %s: %w", pkgDir, err)
		}

		data := BuildScopeData(rd, isCluster)

		docSrc, err := renderDoc(data)
		if err != nil {
			return fmt.Errorf("rendering doc.go for %s/%s: %w", scope, rd.Kind, err)
		}
		if err := writeFile(filepath.Join(pkgDir, "doc.go"), docSrc); err != nil {
			return err
		}

		regSrc, err := renderRegister(data)
		if err != nil {
			return fmt.Errorf("rendering register.go for %s/%s: %w", scope, rd.Kind, err)
		}
		if err := writeFile(filepath.Join(pkgDir, "register.go"), regSrc); err != nil {
			return err
		}

		typesSrc, err := RenderScopeTypes(data)
		if err != nil {
			return fmt.Errorf("rendering types for %s/%s: %w", scope, rd.Kind, err)
		}
		filename := rd.Slug + "_types.go"
		if err := writeFile(filepath.Join(pkgDir, filename), typesSrc); err != nil {
			return err
		}
	}

	return nil
}

// writeFile writes data to path, creating parent directories as needed.
func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return fmt.Errorf("creating dir for %s: %w", path, err)
	}
	if err := os.WriteFile(path, data, 0o600); err != nil {
		return fmt.Errorf("writing %s: %w", path, err)
	}
	return nil
}
